def build_and_export_dataset():
    """
    Export expanded scheme repository to JSON and CSV, then import into SQLite.
    """
    data_dir = os.path.join(os.path.dirname(__file__), "data")
    os.makedirs(data_dir, exist_ok=True)

    json_path = os.path.join(data_dir, "expanded_schemes.json")
    csv_path = os.path.join(data_dir, "expanded_schemes.csv")

    # 1. Write JSON
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(PAN_INDIA_SCHEMES, f, indent=2, ensure_ascii=False)
    print(f"[Data Builder] Successfully compiled {len(PAN_INDIA_SCHEMES)} schemes into {json_path}")

    # 2. Write CSV
    if PAN_INDIA_SCHEMES:
        csv_headers = [
            "id", "title", "acronym", "department", "category", "scope",
            "benefit", "benefit_value", "description", "detailed_description",
            "min_age", "max_age", "gender", "income_max", "occupations", "states",
            "requires_land", "requires_girl_child", "requires_bpl", "criteria_summary",
            "documents", "application_steps", "official_url", "official_application_url",
            "verification_status", "source_dept", "source_title", "last_verified_date",
            "government_level", "beneficiaries", "alternative_names", "scheme_status",
            "source_language"
        ]
        with open(csv_path, "w", encoding="utf-8", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=csv_headers, extrasaction="ignore")
            writer.writeheader()
            for s in PAN_INDIA_SCHEMES:
                row = dict(s)
                # Convert lists to JSON strings for CSV format
                for k in ["occupations", "states", "documents", "application_steps", "beneficiaries", "alternative_names"]:
                    if isinstance(row.get(k), list):
                        row[k] = json.dumps(row[k])
                writer.writerow(row)
        print(f"[Data Builder] Exported CSV dataset to {csv_path}")

    # 3. Import through Import Pipeline
    print("[Data Builder] Ingesting expanded scheme dataset through validation pipeline...")
    summary = import_schemes(PAN_INDIA_SCHEMES, update_existing=True, db_path="backend/schemes.db")
    print("[Data Builder] Import Pipeline Summary:")
    print(f"  - Processed: {summary['records_processed']}")
    print(f"  - Inserted: {summary['records_inserted']}")
    print(f"  - Updated: {summary['records_updated']}")
    print(f"  - Skipped: {summary['duplicate_records_skipped']}")
    print(f"  - Rejected: {summary['invalid_records_rejected']}")
    print(f"  - Needs Review: {summary['records_requiring_verification']}")
    if summary["errors"]:
        print(f"  - Errors: {summary['errors']}")

    # 4. Print updated live statistics
    stats = get_scheme_statistics("backend/schemes.db")
    print("\n[Data Builder] Live Database Statistics:")
    print(f"  - Total Schemes: {stats['total_schemes']}")
    print(f"  - Government Levels: {stats['by_government_level']}")
    print(f"  - Categories: {len(stats['by_category'])} distinct categories")
    print(f"  - Verified Records: {stats['by_verification_status']}")
    
    # State coverage check
    states_covered = sum(1 for st, cnt in stats["state_counts"].items() if cnt > 0)
    uts_covered = sum(1 for ut, cnt in stats["union_territory_counts"].items() if cnt > 0)
    print(f"  - State Coverage: {states_covered} / 28 States covered")
    print(f"  - UT Coverage: {uts_covered} / 8 Union Territories covered")

    return summary, stats


if __name__ == "__main__":
    build_and_export_dataset()
